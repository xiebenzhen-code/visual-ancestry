// 入选规则（逐条都真的执行了，见 work/film-expansion/ 下的审计文件）：
//   1) 只收「影片自己的画面」：Commons 描述/分类明确是 frame / screenshot /
//      scene uit de film / still from … 的扫描件。电影海报、演员肖像、Ross Verlag
//      明星明信片、lobby card、片场花絮照、把普通照片标注成剧照的，全部剔除。
//   2) 每张都逐张向 Commons API 取回 LicenseShortName + Copyrighted，确认为
//      Public domain / Copyrighted=False，并留下当时的描述与分类原文。
//   3) p5.3.2 manifest 里的 5 张重新按文件标题下载、与本地旧文件比 sha256
//      （bytesMatch=true）；p5.8.3-open 的 3 张按 sha1 反查 Commons 命中后再用；
//      其余为本次直接下载（raw2/ 与 frames-build.json 记录了下载 URL 与哈希）。
//   4) imageKind 记录这张图「是什么」——frame（逐帧截图） /
//      scene-still（当年发行/档案的场景照） / publicity-still、
//      publicity-photo（宣传照，但画面即影片场景，逐条注明）。绝不统一说成"剧照"。
//   5) 每张的 visualIntent 都是看过图之后写的，字段值只用
//      services/shootTranslation.js 的 SHOOT_FIELDS 里真实存在的枚举
//      （旧记录里的 elevated / close / PERSON_ONLY 这类越界值列在报告里，逐条修正）。
//
// 被排除的候选（诚实交付，不凑数）：
//   s01 圣女贞德蒙难记 → 电影海报；s20 拿破仑 → Choumoff 人像照；
//   Брунгильда / Siegfrieds death → 明信片（含印上去的片名与演员名）；
//   s15 The Lodger → Commons 检索无同名可核验文件，无法确证身份；
//   s16 Blackmail → 片场宣传照且仅 348x439，画面身份弱；
//   Un chien andalou → CC BY 2.0 / Copyrighted=True，不是公有领域；
//   Potemkin still → 仅 300x255，上墙会被放大；
//   Metropolis lobby card / Hel 海报 → 印刷品，不是画面。

