// Normalize and validate.
export const filmReferences = filmReferenceSeeds.map((seed) => {
  if (!RELATION_TYPES.includes(seed.relationType)) {
    throw new Error(`Invalid relationType "${seed.relationType}" for ${seed.filmTitle}`);
  }
  return {
    artworkId: seed.artworkId,
    filmTitle: seed.filmTitle,
    filmTitleZh: seed.filmTitleZh,
    director: seed.director,
    year: seed.year,
    timestamp: seed.timestamp,
    frameImage: seed.frameImage || null,
    relationType: seed.relationType,
    evidenceLevel: seed.evidenceLevel,
    description: seed.description,
    rightsStatus: seed.rightsStatus || "Film still rights retained by rights holder; metadata reference only, no frame bundled",
    location: seed.location || null,
    locationPattern: seed.locationPattern || null,
  };
});

export function referencesForArtwork(artworkId) {
  return filmReferences.filter((reference) => reference.artworkId === artworkId);
}

export function referencesWithLocation() {
  return filmReferences.filter((reference) => reference.location);
}
